import { mkdir, readFile, writeFile } from "node:fs/promises";

// Edit this list, then run: node scripts/update-sponsors.mjs
const usernames = ["weiuou", "hunterMG", "0xFANGO"];

const avatarSize = 48;
const borderWidth = 1;
const borderColor = "#1f232826";
const outputDirectory = new URL("../sponsors/", import.meta.url);
const readmeFile = new URL("../README.md", import.meta.url);
const sectionPattern =
	/<!-- Badge Sponsors -->[\s\S]*?<!-- End Badge Sponsors -->/;

if (
	usernames.length === 0 ||
	usernames.some(
		(username) =>
			typeof username !== "string" ||
			!/^[a-z\d](?:[a-z\d-]{0,37}[a-z\d])?$/i.test(username),
	)
) {
	throw new Error("Add at least one valid GitHub username to the list.");
}

if (
	new Set(usernames.map((username) => username.toLowerCase())).size !==
	usernames.length
) {
	throw new Error("The sponsor list contains duplicate usernames.");
}

const readme = await readFile(readmeFile, "utf8");
if (!sectionPattern.test(readme)) {
	throw new Error(
		"README.md must contain Badge Sponsors and End Badge Sponsors comments.",
	);
}

// Embed avatars because SVG images in GitHub READMEs cannot load external URLs.
// Finish every download before writing, preserving the existing SVG on failure.
const avatars = await Promise.all(
	usernames.map(async (username) => {
		const response = await fetch(
			`https://github.com/${username}.png?size=${avatarSize * 2}`,
			{
				signal: AbortSignal.timeout(30_000),
			},
		);
		if (!response.ok) {
			throw new Error(
				`Could not download @${username}: HTTP ${response.status}`,
			);
		}
		const type = response.headers.get("content-type")?.split(";")[0].trim();
		if (
			!["image/png", "image/jpeg", "image/gif", "image/webp"].includes(type)
		) {
			throw new Error(`Unexpected image format for @${username}: ${type}`);
		}
		const data = Buffer.from(await response.arrayBuffer());
		if (data.length === 0) {
			throw new Error(`Empty avatar for @${username}`);
		}
		return `data:${type};base64,${data.toString("base64")}`;
	}),
);

function renderAvatar(username, dataUrl) {
	return `<svg xmlns="http://www.w3.org/2000/svg" width="${avatarSize}" height="${avatarSize}" viewBox="0 0 ${avatarSize} ${avatarSize}" role="img" aria-labelledby="title">
\t<!-- Generated by scripts/update-sponsors.mjs. Edit the username list there. -->
\t<title id="title">@${username}</title>
\t<defs>
\t\t<clipPath id="avatar" clipPathUnits="objectBoundingBox">
\t\t\t<circle cx="0.5" cy="0.5" r="0.5" />
\t\t</clipPath>
\t</defs>
\t<image width="${avatarSize}" height="${avatarSize}" clip-path="url(#avatar)"
\t\tpreserveAspectRatio="xMidYMid slice"
\t\thref="${dataUrl}" />
\t<circle cx="${avatarSize / 2}" cy="${avatarSize / 2}" r="${(avatarSize - borderWidth) / 2}"
\t\tfill="none" stroke="${borderColor}" stroke-width="${borderWidth}" />
</svg>\n`;
}

async function writeIfChanged(file, content) {
	const previous = await readFile(file, "utf8").catch((error) => {
		if (error.code !== "ENOENT") throw error;
		return undefined;
	});
	if (previous !== content) {
		await writeFile(file, content);
	}
}

await mkdir(outputDirectory, { recursive: true });
await Promise.all(
	usernames.map((username, index) =>
		writeIfChanged(
			new URL(`${username}.svg`, outputDirectory),
			renderAvatar(username, avatars[index]),
		),
	),
);

const section = `<!-- Badge Sponsors -->
<h3 align="center">Badge Sponsors</h3>
<p align="center">
${usernames.map((username) => `\t<a href="https://github.com/${username}"><img src="./sponsors/${username}.svg" alt="@${username}" /></a>`).join("\n")}
</p>
<!-- End Badge Sponsors -->`;
await writeIfChanged(readmeFile, readme.replace(sectionPattern, section));
console.log(
	`Generated ${usernames.length} sponsor SVGs and updated README.md.`,
);
